#!/bin/bash
# Regenerate every brand-dependent file from addons/studio_intro/brand.json (a new studio name in minutes):
#   jingle (notes follow the letter count), web brand.js + font + jingle, logo PNGs (logo, logo_bg, mark)
#   PREVIEW=1 also renders the MP4/GIF/key-frame preview.  FONT=1 rebuilds the static font from tools/font_src.
# Needs python3 (numpy; fonttools + skia-pathops only for FONT=1), ffmpeg, Godot 4.3+ (GODOT=...), an X display.
set -euo pipefail
K=$(cd "$(dirname "$0")/.." && pwd)
A="$K/addons/studio_intro"; W="$K/studio_intro_web"
G=${GODOT:-/workspace/work/godot47/Godot_v4.7.2-stable_linux.arm64}
mkdir -p "$K/work" "$A/brand" "$W"
python3 -c "import json,sys; json.load(open('$A/brand.json'))" || { echo "brand.json is not valid JSON"; exit 1; }
if [ "${FONT:-0}" = 1 ]; then python3 "$K/tools/make_font.py" "$K/tools/font_src/Fredoka-Variable.ttf" "$A/fonts/Fredoka-Bold.ttf" 700; fi
python3 "$K/tools/make_jingle.py" "$A/brand.json" "$A/audio" "$W"
python3 - "$A/brand.json" "$W/brand.js" <<'PY'
import json, sys
b = json.load(open(sys.argv[1])); b.pop("_doc", None)
for k in ("font", "jingle", "logo_texture", "mark_texture", "audio_bus", "jingle_volume_db"): b.pop(k, None)
b["web_font"] = "Fredoka-Bold.ttf"; b["web_jingle"] = "jingle"
open(sys.argv[2], "w").write("/* generated by tools/make_brand.sh from addons/studio_intro/brand.json - do not edit */\nwindow.STUDIO_BRAND = " + json.dumps(b, indent=2) + ";\n")
print("web: brand.js written")
PY
cp "$A/fonts/Fredoka-Bold.ttf" "$A/fonts/OFL.txt" "$W/"
"$K/tools/sync_demo.sh"
timeout 300 "$G" --headless --path "$K/demo" --import > "$K/work/import.log" 2>&1 || true
MODE=logo OUT="$A/brand" timeout 300 "$G" --rendering-driver opengl3 --path "$K/demo" res://tools/render.tscn > "$K/work/render_logo.log" 2>&1
grep -q "RENDER: done" "$K/work/render_logo.log" || { echo "logo render failed (see work/render_logo.log)"; exit 1; }
# tight crop for the transparent logo (+3% margin), mark stays square
convert "$A/brand/logo.png" -trim +repage -bordercolor none -border 3% "$A/brand/logo.png"
cp "$A/brand/logo.png" "$A/brand/mark.png" "$W/"
"$K/tools/sync_demo.sh"
if [ "${PREVIEW:-0}" = 1 ]; then "$K/tools/preview.sh"; fi
python3 -c "import json; b=json.load(open('$A/brand.json')); print('brand ready:', b['studio_name'])"
